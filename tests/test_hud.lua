local T = dofile((arg[0]:match('^(.*)[/\\]') or '.') .. '/testlib.lua')
local H = require('beamngEarthEnduro/hud')
local calls={}
local h=H.new(function(name,data) calls[#calls+1]={name=name,data=data} end)
T.check(not h:publish({state='READY'},0),'unmounted app gets no updates')
T.check(h:mount(true,0),'first mount recognized')
T.check(h:publish({state='READY',saveAllowed=true},0),'first full state sent')
T.check(not h:publish({state='ERROR'},0.1),'throttle suppresses immediate update')
T.check(h:publish({state='ERROR'},0.25),'changed state sent after throttle')
T.check(not h:publish({state='ERROR'},0.5),'unchanged payload suppressed')
T.check(h:publish({state='ERROR'},2.25),'periodic snapshot resyncs listeners')
T.check(not h:mount(true,3),'heartbeat not a new mount')
h:mount(false,3); T.check(not h:publish({state='READY'},4),'explicit unmount stops updates')
h:mount(true,4); T.check(h:publish({state='READY'},4),'remount gets a full snapshot')
T.check(not h:publish({state='ERROR'},10),'expired heartbeat stops updates')
local broken=H.new(function() error('bridge unavailable') end)
broken:mount(true,0); T.check(not broken:publish({state='READY'},0),'UI bridge failures do not escape')
T.eq(#calls,4,'expected state notifications only')
T.done('HUD publisher')
