#!/usr/bin/env python3
"""Builds the CarKov land map (lua/ge/extensions/beamngEarthEnduro/landmask.lua) from Natural Earth.

Natural Earth is public domain (naturalearthdata.com). The map is a 0.1-degree grid of the places a
CarKov drop or extraction point may land: land, less lakes, less the areas left out below, and less
every cell that touches the sea or a lake, so a point is never right on a coast. Run it again only to
change those areas; the game never runs it.

  python tools/make_land_mask.py            # downloads the Natural Earth files
  python tools/make_land_mask.py --data DIR # or reads ne_50m_*.geojson from DIR
"""
import argparse
import json
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'mod' / 'beamng_earth_enduro' / 'lua' / 'ge' / 'extensions' / 'beamngEarthEnduro' / 'landmask.lua'
SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/{}.geojson'
CELLS_PER_DEGREE = 10
WIDTH, HEIGHT = 360 * CELLS_PER_DEGREE, 180 * CELLS_PER_DEGREE
# Left out because BeamNG.Earth has little map data there: Antarctica (everything south of this
# latitude), these countries, and these deserts (Natural Earth geography region names).
SOUTH_LIMIT = -60
COUNTRIES = {'Greenland'}
DESERTS = {
    'SAHARA', 'LIBYAN DESERT', 'WESTERN DESERT', 'NUBIAN DESERT', 'KALAHARI DESERT', 'RUB’ AL KHALI',
    'GOBI DESERT', 'TAKLIMAKAN DESERT', 'GREAT SANDY DESERT', 'GREAT VICTORIA DESERT', 'Gibson Desert',
}
DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'


def load(name, data):
    if data:
        return json.loads((Path(data) / f'{name}.geojson').read_text(encoding='utf-8'))
    with urllib.request.urlopen(SOURCE.format(name)) as response:
        return json.loads(response.read().decode('utf-8'))


def polygons(geometry):
    if geometry['type'] == 'Polygon':
        return [geometry['coordinates']]
    if geometry['type'] == 'MultiPolygon':
        return geometry['coordinates']
    return []


def paint(draw, features, value, keep=lambda properties: True):
    for feature in features['features']:
        if not keep(feature['properties']):
            continue
        for rings in polygons(feature['geometry']):
            for i, ring in enumerate(rings):
                points = [((lon + 180) * CELLS_PER_DEGREE, (90 - lat) * CELLS_PER_DEGREE) for lon, lat, *_ in ring]
                if len(points) >= 3:
                    # Holes in a land polygon are water; holes in water or a left-out area are left alone.
                    draw.polygon(points, fill=value if i == 0 else (0 if value else None))


def encode(n):
    return DIGITS[n // 1296] + DIGITS[n // 36 % 36] + DIGITS[n % 36]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--data', help='folder holding the ne_50m_*.geojson files')
    args = parser.parse_args()
    image = Image.new('L', (WIDTH, HEIGHT), 0)
    draw = ImageDraw.Draw(image)
    paint(draw, load('ne_50m_land', args.data), 255)
    paint(draw, load('ne_50m_lakes', args.data), 0)
    paint(draw, load('ne_50m_admin_0_countries', args.data), 0,
          lambda p: (p.get('NAME') or p.get('name')) in COUNTRIES)
    paint(draw, load('ne_50m_geography_regions_polys', args.data), 0,
          lambda p: (p.get('NAME') or p.get('name')) in DESERTS)
    draw.rectangle([0, (90 - SOUTH_LIMIT) * CELLS_PER_DEGREE, WIDTH, HEIGHT], fill=0)
    # A cell counts only when it and the eight around it are all land.
    image = image.filter(ImageFilter.MinFilter(3))
    pixels = image.load()
    rows, cells = [], 0
    for y in range(HEIGHT):
        runs, start = [], None
        for x in range(WIDTH + 1):
            land = x < WIDTH and pixels[x, y] > 127
            if land and start is None:
                start = x
            elif not land and start is not None:
                runs.append(encode(start) + encode(x))
                cells += x - start
                start = None
        rows.append(''.join(runs))
    lines = [
        '-- Generated by tools/make_land_mask.py from Natural Earth (public domain). Do not edit by hand.',
        '-- Where a CarKov drop or extraction point may land, on a grid of CELLS_PER_DEGREE cells per degree.',
        '-- rows[1] is the row just south of 90 N; each row lists its land runs as pairs of 3-digit base-36',
        '-- column numbers, first column (0 at 180 W) and the column after the last.',
        f'return {{ CELLS_PER_DEGREE = {CELLS_PER_DEGREE}, WIDTH = {WIDTH}, HEIGHT = {HEIGHT}, rows = {{',
    ]
    lines += [f"'{row}'," for row in rows]
    lines.append('} }')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)}: {cells} land cells, {OUT.stat().st_size} bytes')


if __name__ == '__main__':
    main()
